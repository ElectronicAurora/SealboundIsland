/* ===========================================================================
 * 末环协议 · AI 刻印策略 · smart（残血保命 + 破壁联动 + 精准上色）
 * ---------------------------------------------------------------------------
 * 相对内置 aiPickSeal / aiHitEffect 的改动只有三处，其余全部返回 null 交给内置：
 *
 *   ① 残血保命 —— 内置只看 `maxHp <= 6` 才给 ⑤残锋 高分（130），
 *      标准 30 血局里这条线永远碰不到，等于 ⑤ 在实战中不存在。
 *      但 ⑤ 的收益是「HP 每低 1 点，ATK +1 且 DEF +1」，低血时是全场最猛的一项。
 *      这里改成看**当前**血量与「离临界还差几点」，而不是血上限。
 *
 *      同时顺带修 ⑧b 的用法错误：⑧b 只是「闪避 → 额外回合」的**开关**，只能拿 1 层
 *      （额外回合数 N = ⑧a 层数，叠第 2 层 ⑧b 收益为 0）。内置给 ⑧a 每层只 +14 分，
 *      随机局里几乎永远叠不到，于是 ⑧ 整条线在实战中形同不存在。
 *      这里改成：1 层 ⑧a → 插 1 层 ⑧b 接通 → 之后全部砸 ⑧a（每层 +30% 闪避 + 1 回合）。
 *
 *   ② 破壁联动 —— 内置选印只看自己（血 / 装备 / 回合），完全不看对手。
 *      对手普遍厚尘时，普通攻击会被「DEF + 尘」双重吃掉，正确解只有两条：
 *        · ⑨b 裂帛分支：额外的真实伤害段，绕开 DEF 与尘
 *        · ⑫b 尘梦分支：自己有尘才有增伤，能顶穿尘墙
 *      这里在 `avgFoeDust >= 3` 时把这两项抬到最高优先级。
 *
 *   ③ 精准上色 —— 内置的【灰】只看「第一个候选是不是黑/白/蓝/黄」，
 *      【黑】干脆不用（只封自己已有的）。这里改成：
 *        · 快打死 → 红（撕裂补最后一刀）
 *        · 对方有高伤武器且没蓝 → 蓝
 *        · 对方厚尘 → 灰解【尘】（撕开减伤）
 *        · 对方有 ⑨ / ⑫ 且还没黑过 → 黑掉（预封，他后面选到也废）
 *
 * 三条都做成「有条件才插手」，所以大多数命中仍然走内置逻辑，
 * 不会把 AI 变成只会一套连招的机器。
 * =========================================================================== */

const STRATEGY = {
  name: 'smart：残血保命 + 破壁联动 + 精准上色',

  /* ---------------- 选印 ---------------- */
  pickSeal(ctx) {
    const me = ctx.me, f = ctx.field;
    const owned = id => (me.seals[id] || 0) > 0;
    const cnt = id => me.seals[id] || 0;
    const can = id => ctx.candidates.indexOf(id) >= 0;

    /* ---- ② 破壁联动：对手普遍厚尘，普通攻击打不穿 ---- */
    /* 阈值 3：尘 3 层就能吃掉大部分 1~2 位数的伤害；再多说明全场都在挨挡。
       此时 ⑨b（真实伤害）和 ⑫b（增伤）的价值远超任何常规项。 */
    if (f.avgFoeDust >= 3) {
      if (can('9b')) return '9b';                       // 已有⑨：直接补分支
      if (can('12b')) return '12b';                      // 已有⑫：直接补分支
      if (can('12') && !owned('12')) return '12';         // 没⑫：先把基础拿到（下一轮才有 12b）
      if (can('9') && !owned('9')) return '9';            // 没⑨：同理
    }

    /* ---- ① 残血保命：算「离临界还有几点」，而不是看血上限 ---- */
    /* ⑤ 的公式是 `HP 每比临界低 1 点 → ATK+1 / DEF+1`，临界初始 5（全场共享）。
       所以 `me.hp - 5` 就是现在白拿的加成；血越接近临界，再往里掉就越值。
       实践口径：血 ≤ 60% 上限就算残血，此时 ⑤ 的即时收益已经超过大部分刻印。 */
    const lowRatio = me.maxHp > 0 ? me.hp / me.maxHp : 1;
    const nearCrit = me.hp - 5;                          // >0 表示还没到临界，<=0 表示已经在吃加成
    if (lowRatio <= 0.6) {
      /* ⑧ 凌波：这条线被内置严重低估，但**只有 ⑧a 能叠，⑧b 只能拿 1 层**。
         ── 机制（onDodgeEvade）：
              n = 8a 层数；if (8b > 0 && 8a > 0) grantExtraTurn(n)
            ⑧b 只是「闪避 → 额外回合」这个转换器的**开关**，叠第 2 层毫无收益：
              8a=2 8b=1 → 2 回合 ／ 8a=2 8b=2 → 2 回合 ／ 8a=2 8b=5 → 仍是 2 回合。
            真正成长的是 ⑧a：每层 +30% 闪避，且 N 直接等于层数（双收益）。
             8a=1 → 30% / 1 回合    8a=3 → 90% / 3 回合    8a=4 → 100% / 4 回合
         ── 所以顺序是：先有 1 层 8a（否则 8b 是死分支）→ 插 1 层 8b 接通转换器
            → 之后全部砸 8a，**绝不再拿 8b**。
         ── 但 ⑤ 仍然是残血时的第一优先：它是「攻防双加」的直接数值，
            而 ⑧ 要赌闪避、且第一次接通需要两枚刻印才见效。所以 ⑤ 排在 ⑧ 前面，
            ⑧ 只在「没 ⑤ 可选」或「已经拿到 ⑤」之后才接管。 */
      const aLv = cnt('8a'), bLv = cnt('8b');
      if (can('5')) return '5';                           // 残锋：低血直接换成攻防双加成
      if (aLv >= 1 && bLv < 1 && can('8b')) return '8b';  // 接通转换器：只拿 1 层，之后不再拿
      if (can('8a')) return '8a';                         // 主力成长项：闪避率 + 额外回合数
      /* 没 ⑧a 可选时：残血最怕的是「下一刀就死」，敕罚（4b，先手真伤）更实际 */
      if (can('4b')) return '4b';
      if (nearCrit <= 0 && can('9b')) return '9b';
    }
    /* 血薄上限（如 BOSS 战的 1 HP、自定义 5 HP）时，⑤ 的价值本来就极高 ——
       这条内置其实也有（maxHp<=6 给 130），这里补一个「血上限中等但当前很残」的空档。 */
    if (me.maxHp <= 12 && can('5') && !owned('5')) return '5';

    return null;                                          // 其余全部交给内置评分
  },

  /* ---------------- 分支二选一 ---------------- */
  /* 只有当 pickSeal 返回占位入口 '8' 时才会走到这里（本策略不会，保留给用户改造） */
  pickSealBranch(ctx) {
    if (ctx.baseId !== '8') return null;
    return (ctx.me.seals['8a'] || 0) >= 2 ? '8b' : '8a';
  },

  /* ---------------- 攻击附加色 ---------------- */
  pickPaint(ctx) {
    const t = ctx.target;
    if (!t) return null;
    const can = c => ctx.candidates.indexOf(c) >= 0;

    /* ---- 快打死：红（撕裂是真实伤害，能补最后一刀） ---- */
    /* 阈值用「当前血 ≤ 4」而不是算伤害：策略层拿不到武器细节，
       太精确反而容易误判；4 点以内补撕裂基本稳赚。 */
    if (t.hp <= 4 && can('red')) return 'red';

    /* ---- 高输出目标：蓝（禁它下次攻击） ---- */
    /* atk ≥ 8 是内置同款门槛，保持口径一致 */
    if (t.atk >= 8 && !t.blue && can('blue')) return 'blue';

    /* ---- 厚尘目标：灰解【尘】（撕开减伤通道） ---- */
    /* 灰是即时生效，不占状态位；解掉一层尘等于全场打他都多 1 点伤害 */
    if (t.dust >= 3 && can('grey')) return { color: 'grey', clearKey: 'dust' };

    /* ---- 预封对方的关键刻印：黑 ---- */
    /* 黑的价值在于「他还没拿到也能封」：封 ⑨ 断撕裂、封 ⑫ 断尘增伤。
       只封这两项 —— 封别的收益不明显，还会浪费一次命中附加。
       ⚠ 判断顺序有讲究：
         · ⑫ 已经在叠（层数 > 0）→ 立刻断，这是即时止损；
         · ⑨ 只要还没黑过就封 —— 它是全场最高频的伤害来源，且"预先封锁"本身就值
           （他后面选到 ⑨ 也直接失效），不必等他先拿到。
       两项都不重复封（blacked 里已有的跳过）。 */
    if (can('black')) {
      const blacked = t.blacked || [];
      if ((t.seals['12'] || 0) > 0 && blacked.indexOf('12') < 0) {
        return { color: 'black', sealId: '12' };          // ⑫ 正在叠：即时断掉增伤
      }
      if (blacked.indexOf('9') < 0) {
        return { color: 'black', sealId: '9' };           // ⑨ 预封：断撕裂源头
      }
    }

    return null;                                          // 其余交给内置
  }
};
